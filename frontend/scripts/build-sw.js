#!/usr/bin/env node
// Post-build step for the web export (run after `expo export --platform web --output-dir dist`).
// 1. Writes dist/sw.js: a service worker that precaches every file of THIS build, so the whole app
//    (including screens opened for the first time) works offline after the first visit.
// 2. Writes dist/404.html (copy of index.html) as an SPA fallback for static hosts without rewrites.
// No API or cross-origin request is ever cached.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const DIST = path.join(__dirname, "..", "dist");
if (!fs.existsSync(path.join(DIST, "index.html"))) {
  console.error("dist/index.html tidak ditemukan. Jalankan `npx expo export --platform web --output-dir dist` dulu.");
  process.exit(1);
}

const SKIP = new Set(["sw.js", "404.html", "metadata.json", "_redirects", "_headers"]);
const files = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else {
      const rel = path.relative(DIST, full).split(path.sep).join("/");
      if (!SKIP.has(rel) && !rel.endsWith(".map")) files.push(rel);
    }
  }
})(DIST);
files.sort();

// The version changes whenever any file changes, so a new deploy installs a new cache.
const hash = crypto.createHash("sha256");
hash.update(fs.readFileSync(__filename)); // a change in the service worker logic is a new version too
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(DIST, f)));
const version = hash.digest("hex").slice(0, 12);
const bytes = files.reduce((n, f) => n + fs.statSync(path.join(DIST, f)).size, 0);

const sw = `// Generated by scripts/build-sw.js. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "usahora-" + VERSION;
const PRECACHE = ${JSON.stringify(files.map((f) => "/" + f))};

const SHELL = "/index.html";

// Many hosts (and \`serve\`) redirect /index.html to /. Browsers refuse a redirected response for a
// page navigation, so store a clean (non-redirected) copy of every file.
async function put(cache, url) {
  const res = await fetch(url, { cache: "reload" });
  if (!res.ok) throw new Error("precache gagal: " + url + " (" + res.status + ")");
  const clean = res.redirected ? new Response(await res.blob(), { status: res.status, statusText: res.statusText, headers: res.headers }) : res;
  await cache.put(url, clean);
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => Promise.all(PRECACHE.map((u) => put(c, u))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("usahora-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Tapping a reminder notification opens (or focuses) USAHORA.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => (list.length ? list[0].focus() : self.clients.openWindow("/"))),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never cache other servers
  if (url.pathname.startsWith("/api/") || url.searchParams.has("token")) return; // never cache API / private files

  if (req.mode === "navigate") {
    // App shell: try the network (fresh deploys), fall back to the cached shell when offline.
    event.respondWith(
      fetch(req)
        .then((res) => (res.ok || res.status === 404 ? res : Promise.reject(new Error(String(res.status)))))
        .catch(() => caches.open(CACHE).then((c) => c.match(SHELL)).then((hit) => hit || Response.error())),
    );
    return;
  }
  // Static files of this build: cache first (file names contain a content hash).
  event.respondWith(
    caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok && res.type === "basic") {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    })),
  );
});
`;
fs.writeFileSync(path.join(DIST, "sw.js"), sw);
fs.copyFileSync(path.join(DIST, "index.html"), path.join(DIST, "404.html"));
console.log(`dist/sw.js: versi ${version}, ${files.length} file (${(bytes / 1024 / 1024).toFixed(2)} MB) di-precache`);
console.log("dist/404.html: fallback SPA");
